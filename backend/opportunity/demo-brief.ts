/** Terms the business already uses on its own site. Observed, not researched. */
function observedTerms(pages: CrawledPage[], sector: string | null): string[] {
  const terms = new Set<string>();

  for (const page of pages) {
    if (page.state !== "OK" && page.state !== "REDIRECT") continue;
    for (const heading of page.h1) {
      const cleaned = heading.trim();
      if (cleaned.length > 3 && cleaned.length < 60) terms.add(cleaned);
    }
  }

  if (sector) terms.add(sector);
  return [...terms].slice(0, 12);
}

export interface BuildBriefOptions {
  /** Overrides the sector when the input data has none. */
  sector?: string;
}

export function buildDemoBrief(record: OpportunityRecord, options: BuildBriefOptions = {}): DemoBrief {
  const { business, problems, analysis } = record;
  const sector = business.sector ?? options.sector ?? null;
  const template = sectorTemplate(sector);
  const crawledPages = analysis?.site?.site.pages ?? [];

  const existingPaths = new Set(
    crawledPages
      .filter((page) => page.state === "OK")
      .map((page) => {
        try {
          return new URL(page.url).pathname.replace(/\.html?$/, "").replace(/\/$/, "") || "/";
        } catch {
          return page.url;
        }
      })
  );

  const pages: BriefPage[] = SECTOR_PAGES[template].map((page, index, all) => ({
    path: page.path,
    title: page.title,
    purpose: page.purpose,
    rationale:
      index === 0
        ? "Es donde aterriza la mayoría del tráfico, así que carga con la conversión principal."
        : `Responde a una intención de búsqueda propia: quien busca esto no busca lo mismo que en ${all[0].path}.`,
    sections: page.sections,
    primaryCta: page.cta,
    // Everything links back to the contact page, and the homepage links to all.
    linksTo: index === 0 ? all.slice(1).map((other) => other.path) : ["/", all[all.length - 1].path],
    existsToday: existingPaths.has(page.path),
  }));

  const placeholders: string[] = [];
  const askClientFor: string[] = [];

  if (business.phone === null) {
    placeholders.push("phone");
    askClientFor.push("Teléfono de contacto que quiere mostrar en la web.");
  }
  if (business.rating === null || business.reviewCount === null) {
    placeholders.push("reviews");
    askClientFor.push("Acceso a sus reseñas reales para poder mostrarlas (no se inventará ninguna).");
  }
  // Images are never invented. A demo shows a real photo or an obvious blank.
  placeholders.push("images");
  askClientFor.push("Fotografías reales del negocio: la demo usará marcadores hasta tenerlas.");
  askClientFor.push("Dirección postal completa y horarios exactos, para el schema de negocio local.");

  const valueProposition =
    business.rating !== null && business.reviewCount !== null && business.reviewCount >= 20
      ? fact(
          `${business.name}: ${business.rating}★ sobre ${business.reviewCount} reseñas${business.city ? ` en ${business.city}` : ""}.`,
          "VERIFIED",
          "Valoración y reseñas de los datos de entrada."
        )
      : fact<string>(null, "PLACEHOLDER", "Sin reseñas suficientes para construir una propuesta de valor verificable.");

  if (valueProposition.status === "PLACEHOLDER") placeholders.push("valueProposition");

  return {
    business: {
      name: fact(business.name, "VERIFIED", "Dato de entrada."),
      sector: fact(sector, sector ? "VERIFIED" : "UNKNOWN", "Dato de entrada."),
      city: fact(business.city, business.city ? "VERIFIED" : "UNKNOWN", "Dato de entrada."),
      phone: fact(business.phone, business.phone ? "VERIFIED" : "UNKNOWN", "Dato de entrada."),
      website: fact(business.website, business.website ? "VERIFIED" : "UNKNOWN", "Dato de entrada."),
      rating: fact(business.rating, business.rating !== null ? "VERIFIED" : "UNKNOWN", "Dato de entrada."),
      reviewCount: fact(business.reviewCount, business.reviewCount !== null ? "VERIFIED" : "UNKNOWN", "Dato de entrada."),
    },
    improvesOn: problems.map((problem) => ({
      problem: problem.statement,
      howTheDemoFixesIt: PROBLEM_FIXES[problem.area],
    })),
    valueProposition,
    audience: fact(
      sector && business.city ? `Clientes de ${sector.toLowerCase()} en ${business.city} y alrededores.` : null,
      sector && business.city ? "PROBABLE" : "UNKNOWN",
      "Inferido del sector y la localidad, no de datos de audiencia reales."
    ),
    pages,
    conversionGoals: [pages[0].primaryCta, "Llamada telefónica", "Mensaje de WhatsApp"],
    seo: {
      observedTerms: observedTerms(crawledPages, sector),
      titlePattern: business.city
        ? `{página} — ${business.name} en ${business.city}`
        : `{página} — ${business.name}`,
      schemaTypes:
        template === "restaurante"
          ? ["Restaurant", "LocalBusiness"]
          : template === "clinica"
            ? ["MedicalBusiness", "LocalBusiness"]
            : ["LocalBusiness", "Service"],
      localSeo: business.city !== null,
    },
    design: {
      direction:
        template === "restaurante"
          ? "Fotografía grande y tipografía con carácter: en hostelería la decisión es visual."
          : template === "clinica"
            ? "Sobrio, mucho blanco y jerarquía clara: la confianza se transmite con orden."
            : "Directo y funcional, con el contacto siempre visible: aquí se compra por urgencia.",
      rationale: `Elegido por el sector (${sector ?? "no especificado"}), no por gusto.`,
      observedBrandSignals: crawledPages
        .filter((page) => page.state === "OK" && page.title)
        .slice(0, 3)
        .map((page) => `Title actual: "${page.title}"`),
    },
    placeholders,
    askClientFor,
  };
}
