/**
 * The DEMO_BRIEF: the handover from analysis to construction.
 *
 * Everything the build engine needs to produce a page for *this* business and
 * no other, and — just as important — an explicit register of what is known
 * versus what is a placeholder. A build engine that cannot tell the two apart
 * will happily invent an address, and inventing a business's address is the
 * single fastest way to destroy a sales conversation.
 *
 * Nothing here is generated by a language model. Every field is either copied
 * from verified input, derived from a measurement, or marked PLACEHOLDER.
 */

export type FactStatus = "VERIFIED" | "PROBABLE" | "PLACEHOLDER" | "UNKNOWN";

export interface BriefFact<T> {
  value: T | null;
  status: FactStatus;
  /** Where it came from, so the build engine can decide whether to show it. */
  source: string;
}

export interface BriefPage {
  path: string;
  title: string;
  purpose: string;
  /** Why this page exists at all. No page without a reason. */
  rationale: string;
  sections: string[];
  primaryCta: string;
  /** Pages this one should link to, for the internal-linking plan. */
  linksTo: string[];
  /** Whether the current site already has something equivalent. */
  existsToday: boolean;
}

export interface DemoBrief {
  business: {
    name: BriefFact<string>;
    sector: BriefFact<string>;
    city: BriefFact<string>;
    phone: BriefFact<string>;
    website: BriefFact<string>;
    rating: BriefFact<number>;
    reviewCount: BriefFact<number>;
  };
  /** What the demo must visibly beat, taken from the real diagnosis. */
  improvesOn: { problem: string; howTheDemoFixesIt: string }[];
  /** The value proposition, assembled from verified facts only. */
  valueProposition: BriefFact<string>;
  audience: BriefFact<string>;
  pages: BriefPage[];
  /** Conversion actions, ordered. First one is the page's main job. */
  conversionGoals: string[];
  seo: {
    /** Terms the business itself already uses. Not keyword research. */
    observedTerms: string[];
    titlePattern: string;
    schemaTypes: string[];
    localSeo: boolean;
  };
  design: {
    direction: string;
    rationale: string;
    /** Never invented: only what the current site actually shows. */
    observedBrandSignals: string[];
  };
  /** Fields the build engine must NOT render as fact. */
  placeholders: string[];
  /** What we do not know and would need from the client. */
  askClientFor: string[];
}

