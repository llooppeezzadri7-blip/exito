/** Maps a free-text sector onto one of the known structures. */
export function sectorTemplate(sector: string | null): keyof typeof SECTOR_PAGES {
  const value = (sector ?? "").toLowerCase();

  if (/restaurant|bar|caf|pizzer|marisqu|cocina|gastro/.test(value)) return "restaurante";
  if (/taller|mec[aá]nic|autom|neum[aá]tic|chapa/.test(value)) return "taller";
  if (/cl[ií]nic|dental|dentist|m[eé]dic|fisio|est[eé]tic|psic/.test(value)) return "clinica";
  return "servicios";
}

function fact<T>(value: T | null | undefined, status: FactStatus, source: string): BriefFact<T> {
  return { value: value ?? null, status: value === null || value === undefined ? "UNKNOWN" : status, source };
}

